#!/usr/bin/env node
/**
 * Bundle F&O API Worker for Cloudflare Workers Builds.
 * Output: dist/worker.js (referenced by wrangler.toml main)
 *
 * Optional: BUILD_PAGES_FUNCTIONS=1 also emits functions/api/[[path]].js
 */

import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import esbuild from 'esbuild';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const stubs = path.join(root, 'cloudflare', 'stubs');
const workerOut = path.join(root, 'dist', 'worker.js');
const pagesOut = path.join(root, 'functions', 'api', '[[path]].js');

const shared = {
  absWorkingDir: root,
  bundle: true,
  platform: 'neutral',
  format: 'esm',
  target: ['es2022'],
  conditions: ['worker', 'browser', 'import', 'default'],
  mainFields: ['module', 'main'],
  inject: [path.join(root, 'cloudflare', 'process-shim.js')],
  alias: {
    fs: path.join(stubs, 'fs.js'),
    'node:fs': path.join(stubs, 'fs.js'),
    path: path.join(stubs, 'path.js'),
    'node:path': path.join(stubs, 'path.js'),
    dotenv: path.join(stubs, 'dotenv.js'),
    otplib: path.join(stubs, 'otplib.js'),
  },
  external: ['node:sqlite', 'sqlite', 'ws', 'express'],
  logLevel: 'info',
  legalComments: 'none',
};

function rewriteNamedExport(outfile, exportName) {
  let raw = fs.readFileSync(outfile, 'utf8');
  raw = raw.replace(new RegExp(`\\nexport \\{ ${exportName} \\};\\s*$`, 'm'), '\n');
  const replaced = raw.replace(
    /export default (require_[\w$]+)\(\);/,
    `const __powerbullEntry = $1();\nexport const ${exportName} = __powerbullEntry.${exportName};\nexport default __powerbullEntry.default || { ${exportName}: __powerbullEntry.${exportName} };`,
  );
  if (replaced === raw) {
    console.warn(`Warning: could not rewrite ${exportName} export in ${path.relative(root, outfile)}`);
    fs.writeFileSync(outfile, raw);
    return;
  }
  fs.writeFileSync(outfile, replaced);
}

/** Workers have no Node path globals; CJS backend files still reference them. */
const workerDefines = {
  'process.env.NODE_ENV': '"production"',
  __dirname: JSON.stringify('/'),
  __filename: JSON.stringify('/worker.js'),
};

async function buildWorker() {
  fs.mkdirSync(path.dirname(workerOut), { recursive: true });
  await esbuild.build({
    ...shared,
    entryPoints: [path.join(root, 'cloudflare', 'worker.js')],
    outfile: workerOut,
    define: workerDefines,
    banner: {
      js: [
        '/* PowerBull Pro — Cloudflare Worker (generated by scripts/build-cloudflare.mjs) */',
        // Safety net if any free __dirname slips past define (e.g. dynamic access).
        'var __dirname = "/"; var __filename = "/worker.js";',
      ].join('\n'),
    },
  });

  // IMPORTANT: do NOT `export const fetch = …`.
  // A named ESM export named `fetch` shadows globalThis.fetch for the whole
  // bundle. Backend code then calls the Worker handler as if it were HTTP
  // fetch → `new URL(request.url)` throws "Invalid URL string." and NSE/Dhan
  // fall back to mock. Default export { fetch } is enough for Cloudflare.
  let raw = fs.readFileSync(workerOut, 'utf8');
  raw = raw.replace(/\nexport \{ fetch, default \};\s*$/m, '\n');
  raw = raw.replace(/\nexport const fetch = [^;]+;\s*$/m, '\n');
  const replaced = raw.replace(
    /export default (require_[\w$]+)\(\);/,
    `const __powerbullWorker = $1();\nexport default __powerbullWorker.default || { fetch: __powerbullWorker.fetch };`,
  );
  if (replaced === raw) {
    if (/fetch/.test(raw)) {
      fs.appendFileSync(workerOut, '\nexport default { fetch };\n');
      console.warn('Warning: appended default export { fetch } — verify dist/worker.js');
    } else {
      console.warn('Warning: could not rewrite Worker default export — check dist/worker.js');
      fs.writeFileSync(workerOut, raw);
    }
  } else {
    fs.writeFileSync(workerOut, replaced);
  }

  const size = fs.statSync(workerOut).size;
  console.log(`Cloudflare Worker bundle written: ${path.relative(root, workerOut)} (${Math.round(size / 1024)} KB)`);
}

async function buildPagesFunction() {
  fs.mkdirSync(path.dirname(pagesOut), { recursive: true });
  await esbuild.build({
    ...shared,
    entryPoints: [path.join(root, 'cloudflare', 'entry.js')],
    outfile: pagesOut,
    define: workerDefines,
    banner: {
      js: [
        '/* PowerBull Pro — Cloudflare Pages Function (optional) */',
        'var __dirname = "/"; var __filename = "/worker.js";',
      ].join('\n'),
    },
  });
  rewriteNamedExport(pagesOut, 'onRequest');
  const size = fs.statSync(pagesOut).size;
  console.log(`Cloudflare Pages Function bundle written: ${path.relative(root, pagesOut)} (${Math.round(size / 1024)} KB)`);
}

async function main() {
  await buildWorker();
  // Do not emit functions/ by default — a functions/ folder can confuse Workers Builds.
  if (process.env.BUILD_PAGES_FUNCTIONS === '1') {
    await buildPagesFunction();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
