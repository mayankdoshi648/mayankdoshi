#!/usr/bin/env node
/**
 * Bundle F&O API handler for Cloudflare Pages Functions.
 * Output: functions/api/[[path]].js (ESM onRequest export)
 */

import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import esbuild from 'esbuild';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const outfile = path.join(root, 'functions', 'api', '[[path]].js');
const stubs = path.join(root, 'cloudflare', 'stubs');

async function main() {
  fs.mkdirSync(path.dirname(outfile), { recursive: true });

  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: [path.join(root, 'cloudflare', 'entry.js')],
    outfile,
    bundle: true,
    platform: 'neutral',
    format: 'esm',
    target: ['es2022'],
    conditions: ['worker', 'browser', 'import', 'default'],
    mainFields: ['module', 'main'],
    inject: [path.join(root, 'cloudflare', 'process-shim.js')],
    alias: {
      fs: path.join(stubs, 'fs.js'),
      'node:fs': path.join(stubs, 'fs.js'),
      path: path.join(stubs, 'path.js'),
      'node:path': path.join(stubs, 'path.js'),
      dotenv: path.join(stubs, 'dotenv.js'),
      otplib: path.join(stubs, 'otplib.js'),
    },
    external: ['node:sqlite', 'sqlite', 'ws', 'express'],
    logLevel: 'info',
    legalComments: 'none',
    banner: {
      js: '/* PowerBull Pro — Cloudflare Pages Function (generated by scripts/build-cloudflare.mjs) */',
    },
  });

  let raw = fs.readFileSync(outfile, 'utf8');
  raw = raw.replace(/\nexport \{ onRequest \};\s*$/m, '\n');

  // esbuild CJS→ESM emits `export default require_*(());` — re-export onRequest for Pages Functions
  const replaced = raw.replace(
    /export default (require_[\w$]+)\(\);/,
    'const __powerbullEntry = $1();\nexport const onRequest = __powerbullEntry.onRequest;\nexport default __powerbullEntry;',
  );
  if (replaced === raw) {
    console.warn('Warning: could not rewrite onRequest export — check bundle manually');
  }
  fs.writeFileSync(outfile, replaced);

  void result;
  const size = fs.statSync(outfile).size;
  console.log(`Cloudflare function bundle written: ${path.relative(root, outfile)} (${Math.round(size / 1024)} KB)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
